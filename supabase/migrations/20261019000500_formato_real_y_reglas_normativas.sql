-- 5. Procesos didácticos por área, configurables por institución.
--    Verificado: la expresión "procesos didácticos" aparece CERO veces en el CNEB
--    y CERO veces en el Programa Curricular de Primaria. Son práctica instalada,
--    no norma, y por eso cuelgan de la institución y llevan origen explícito.
create table if not exists public.procesos_didacticos (
    id bigint generated by default as identity primary key,
    institucion_id bigint references public.instituciones_educativas(id),
    area_curricular_id bigint not null references public.areas_curriculares(id),
    competencia_id bigint references public.competencias(id),
    nombre varchar(180) not null,
    origen varchar(20) not null default 'PRACTICA_IE'
        check (origen in ('PRACTICA_IE', 'NORMA', 'PROPUESTA')),
    nota_fuente text,
    activo boolean not null default true,
    created_at timestamptz not null default now()
);

comment on table public.procesos_didacticos is
    'Secuencia del momento de desarrollo, propia de cada área. No está en el currículo: '
    'origen por defecto PRACTICA_IE. institucion_id nulo = plantilla base sugerida.';

create table if not exists public.pasos_proceso_didactico (
    id bigint generated by default as identity primary key,
    proceso_id bigint not null references public.procesos_didacticos(id) on delete cascade,
    orden smallint not null check (orden > 0),
    nombre varchar(180) not null,
    descripcion text,
    unique (proceso_id, orden)
);

alter table public.actividades_sesion
