-- Ajustes derivados de dos fuentes verificadas en octubre de 2026:
--   (a) material real cedido por una docente de 4.º grado (dos sesiones y sus fichas);
--   (b) normativa vigente: CNEB RM 281-2016, Programa Curricular RM 649-2016,
--       RVM 094-2020 modificada por RVM 048-2024, RM 501-2025.
-- Objetivo: que la base pueda representar el documento real y hacer cumplir las
-- reglas de evaluación sin depender de la aplicación.

-- 1. El instrumento que realmente usan las docentes es la escala de valoración.
--    El check anterior no la admitía.
alter table public.instrumentos_evaluacion
    drop constraint if exists instrumentos_evaluacion_tipo_check;

alter table public.instrumentos_evaluacion
    add constraint instrumentos_evaluacion_tipo_check
    check (tipo in ('RUBRICA', 'LISTA_COTEJO', 'ESCALA_VALORACION',
                    'REGISTRO', 'PORTAFOLIO', 'OTRO'));

-- 2. Trazabilidad a la página, no solo a la URL. Es el diferenciador del producto:
--    poder decir "Programa Curricular de Primaria, p. 139".
alter table public.desempenos_grado
    add column if not exists fuente_pagina varchar(20),
    add column if not exists exige_material_concreto boolean not null default false;

comment on column public.desempenos_grado.exige_material_concreto is
    'Verdadero cuando el texto del desempeño exige material concreto. Verificado: la '
    'expresión aparece 7 veces en las 212 pp. del Programa Curricular, siempre dentro '
    'de desempeños específicos. No existe norma que lo exija de forma general.';

alter table public.estandares_aprendizaje
    add column if not exists fuente_url text,
    add column if not exists fuente_pagina varchar(20);

-- 3. Enfoques transversales con sus acciones observables (bloque III del formato real).
create table if not exists public.enfoques_transversales (
    id smallint generated by default as identity primary key,
    version_curricular_id bigint not null references public.versiones_curriculares(id),
    codigo varchar(40) not null,
    nombre varchar(180) not null,
    unique (version_curricular_id, codigo)
);

create table if not exists public.sesiones_enfoques (
    sesion_id bigint not null references public.sesiones_planificadas(id) on delete cascade,
    enfoque_id smallint not null references public.enfoques_transversales(id),
    accion_observable text not null,
    primary key (sesion_id, enfoque_id)
);

