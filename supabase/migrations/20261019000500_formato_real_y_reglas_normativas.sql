-- 6. Materiales, distinguiendo lo que el desempeño exige de lo que la docente elige.
create table if not exists public.materiales_educativos (
    id bigint generated by default as identity primary key,
    institucion_id bigint references public.instituciones_educativas(id),
    nombre varchar(180) not null,
    tipo varchar(24) not null default 'CONCRETO'
        check (tipo in ('CONCRETO', 'IMPRESO', 'DIGITAL', 'FUNGIBLE', 'OTRO')),
    es_estructurado_minedu boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.sesiones_materiales (
    id bigint generated by default as identity primary key,
    sesion_id bigint not null references public.sesiones_planificadas(id) on delete cascade,
    material_id bigint references public.materiales_educativos(id),
    descripcion varchar(240),
    cantidad smallint check (cantidad is null or cantidad > 0),
    caracter varchar(16) not null default 'SUGERIDO'
        check (caracter in ('OBLIGATORIO', 'SUGERIDO')),
    desempeno_id bigint references public.desempenos_grado(id),
    check (material_id is not null or descripcion is not null),
    check (caracter <> 'OBLIGATORIO' or desempeno_id is not null)
);

comment on column public.sesiones_materiales.caracter is
    'OBLIGATORIO solo cuando un desempeño lo exige, y entonces desempeno_id es obligatorio '
    'para poder mostrar la fuente. En cualquier otro caso es SUGERIDO.';

-- 7. RVM 048-2024: en primaria la conclusión descriptiva es obligatoria en B y en C;
--    en los demás niveles, solo en C. Y en todos los casos debe incluir recomendaciones
--    personalizadas. Como la regla depende del nivel educativo del estudiante, no cabe
--    en un CHECK: va en un trigger.
create or replace function public.fn_valida_conclusion_descriptiva()
returns trigger
language plpgsql
as $$
declare
    v_nivel varchar(20);
    v_exige boolean;
begin
    if new.estado <> 'EVALUADA' or new.nivel_logro is null then
        return new;
    end if;

    select ne.codigo
      into v_nivel
      from public.ubicaciones_matricula um
      join public.secciones s on s.id = um.seccion_id
      join public.grados_educativos g on g.id = s.grado_id
      join public.niveles_educativos ne on ne.id = g.nivel_id
     where um.matricula_id = new.matricula_id
     order by um.fecha_inicio desc
     limit 1;

    if v_nivel is null then
        return new;
    end if;

    if upper(v_nivel) like '%PRIM%' then
        v_exige := new.nivel_logro in ('B', 'C');
    else
        v_exige := new.nivel_logro = 'C';
    end if;

    if v_exige then
        if new.conclusion_descriptiva is null
           or btrim(new.conclusion_descriptiva) = '' then
            raise exception
                'La conclusión descriptiva es obligatoria con nivel de logro % en %. '
                'RVM N.º 094-2020-MINEDU modificada por RVM N.º 048-2024-MINEDU.',
                new.nivel_logro, v_nivel;
        end if;
        if new.recomendacion is null or btrim(new.recomendacion) = '' then
            raise exception
                'La conclusión descriptiva debe incluir recomendaciones personalizadas '
                'orientadas al desarrollo de la competencia. RVM N.º 048-2024-MINEDU.';
        end if;
    end if;

    return new;
end;
$$;

drop trigger if exists tg_valida_conclusion_descriptiva on public.progreso_competencias;
create trigger tg_valida_conclusion_descriptiva
    before insert or update on public.progreso_competencias
    for each row execute function public.fn_valida_conclusion_descriptiva();

-- 8. Las dos reglas que cruzan periodos y que ningún CHECK puede expresar.
--    RVM 048-2024, 5.1.1.3: cada competencia debe trabajarse en más de un periodo,
--    y al cerrar el año todas deben tener nivel asignado.
create or replace view public.v_cobertura_competencias_periodo as
select
    m.anio_escolar_id,
    pc.matricula_id,
    pc.competencia_id,
    count(distinct pc.periodo_evaluacion_id) filter (where pc.estado = 'EVALUADA')
        as periodos_evaluados,
    count(*) filter (where pc.estado = 'EVALUADA' and pc.nivel_logro = 'C')
        as periodos_en_c,
    max(pc.nivel_logro) filter (where pc.estado = 'EVALUADA') as ultimo_nivel_registrado
from public.progreso_competencias pc
join public.matriculas m on m.id = pc.matricula_id
group by m.anio_escolar_id, pc.matricula_id, pc.competencia_id;

comment on view public.v_cobertura_competencias_periodo is
    'Soporte de la regla de la RVM 048-2024: cada competencia en más de un periodo. '
    'periodos_evaluados <= 1 al cerrar el año es incumplimiento.';

create or replace view public.v_conclusiones_pendientes as
select
    pc.id as progreso_id,
    pc.matricula_id,
    pc.competencia_id,
    pc.periodo_evaluacion_id,
    pc.nivel_logro,
    (pc.conclusion_descriptiva is null or btrim(pc.conclusion_descriptiva) = '')
        as falta_conclusion,
    (pc.recomendacion is null or btrim(pc.recomendacion) = '')
        as falta_recomendacion
from public.progreso_competencias pc
where pc.estado = 'EVALUADA'
  and pc.nivel_logro in ('B', 'C')
  and (pc.conclusion_descriptiva is null or btrim(pc.conclusion_descriptiva) = ''
       or pc.recomendacion is null or btrim(pc.recomendacion) = '');

