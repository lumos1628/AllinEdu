-- La jornada del docente como dato citable, no como número suelto en el código.
-- Fuente: D.S. N.º 004-2013-ED, Reglamento de la Ley N.º 29944, artículo 139
-- "Jornada del profesor con aula a cargo", MODIFICADO por el artículo 1 del
-- D.S. N.º 005-2017-MINEDU (publicado el 19 de mayo de 2017), cuyo texto dice
-- que la jornada "puede ser lectiva o no lectiva".
-- Verificado sobre el PDF el 19-10-2026: no hay modificación posterior.

create table if not exists public.jornadas_normativas (
    id smallint generated by default as identity primary key,
    nivel_id smallint not null references public.niveles_educativos(id),
    modalidad varchar(8) not null default 'EBR'
        check (modalidad in ('EBR', 'EBE', 'EBA')),
    horas_pedagogicas smallint not null check (horas_pedagogicas > 0),
    minutos_hora_pedagogica smallint not null default 45,
    norma varchar(120) not null,
    articulo varchar(40) not null,
    nota text,
    unique (nivel_id, modalidad)
);

comment on table public.jornadas_normativas is
    'Horas de la jornada del profesor con aula a cargo. Ninguna norma reparte estas '
    'horas entre lectivas y no lectivas: el reglamento no define los términos. Al '
    'personal jerárquico sí se le fija el dictado (art. 141: 40 horas con 12 de clase).';

insert into public.jornadas_normativas
    (nivel_id, modalidad, horas_pedagogicas, norma, articulo, nota)
select n.id, 'EBR', x.horas,
       'D.S. N.º 004-2013-ED, modificado por D.S. N.º 005-2017-MINEDU',
       'Artículo 139',
       'La jornada "puede ser lectiva o no lectiva"; el reglamento no fija la proporción.'
from public.niveles_educativos n
join (values ('PRIMARIA', 35::smallint), ('SECUNDARIA', 33::smallint)) as x(cod, horas)
     on x.cod = n.codigo
on conflict (nivel_id, modalidad) do update
    set horas_pedagogicas = excluded.horas_pedagogicas,
        norma = excluded.norma,
        articulo = excluded.articulo,
        nota = excluded.nota;

-- El planteamiento del problema, calculado desde los datos en lugar de afirmado.
-- Compara las horas que la docente realmente dicta con su jornada normativa y
-- reparte el resto entre las sesiones que le corresponden.
create or replace view public.v_carga_no_programada as
with dicta as (
    select
        s.id                                            as seccion_id,
        s.nombre                                        as seccion,
        g.numero                                        as grado,
        g.nivel_id,
        ad.cuenta_usuario_id,
        sum(pa.horas_pedagogicas)                       as horas_que_dicta
    from public.ofertas_curriculares oc
    join public.secciones s on s.id = oc.seccion_id
    join public.grados_educativos g on g.id = s.grado_id
    join public.planes_estudio_areas pa on pa.id = oc.plan_estudio_area_id
    join public.asignaciones_docentes_areas ada
         on ada.oferta_curricular_id = oc.id and ada.vigente_hasta is null
    join public.asignaciones_docentes ad
         on ad.cuenta_usuario_id = ada.cuenta_usuario_id
        and ad.seccion_id = s.id and ad.vigente_hasta is null
    group by s.id, s.nombre, g.numero, g.nivel_id, ad.cuenta_usuario_id
)
select
    d.seccion_id,
    d.seccion,
    d.grado,
    d.cuenta_usuario_id,
    d.horas_que_dicta,
    j.horas_pedagogicas                                     as horas_jornada,
    j.horas_pedagogicas - d.horas_que_dicta                 as horas_no_lectivas,
    ceil(d.horas_que_dicta / 2.0)::int                      as sesiones_semanales,
    round(
        (j.horas_pedagogicas - d.horas_que_dicta) * j.minutos_hora_pedagogica
        / nullif(ceil(d.horas_que_dicta / 2.0), 0), 1
    )                                                       as minutos_por_sesion,
    j.norma,
    j.articulo
from dicta d
join public.jornadas_normativas j
     on j.nivel_id = d.nivel_id and j.modalidad = 'EBR';

comment on view public.v_carga_no_programada is
    'Minutos de jornada no lectiva disponibles por sesión. Asume bloques de 2 horas '
    'pedagógicas (90 minutos). Es el indicador del planteamiento del problema: si el '
    'resultado es mucho menor que el tiempo real de preparación, el trabajo ocurre '
    'fuera de la jornada.';
