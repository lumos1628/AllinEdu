-- El telar: generación de sesiones por unidad, revisión por nudos y el contexto del aula.
-- Ver ALCANCE.md §3, USE_CASES.md (UC-01, UC-04, UC-22) y DATABASE.md.

-- 1. Mi aula: lo que el generador debe saber del aula y la comunidad del docente.
--    Lo escribe el docente con sus palabras, una vez. Nunca lleva datos de estudiantes.
create table if not exists public.contextos_aula (
    cuenta_usuario_id bigint primary key references public.cuentas_usuario(id) on delete cascade,
    texto text not null default '' check (char_length(texto) <= 2000),
    updated_at timestamptz not null default now()
);

comment on table public.contextos_aula is
    'Contexto que el docente escribe para sus borradores: comunidad, materiales que tiene, '
    'costumbres del aula. Se envía al generador; por eso no debe contener datos de estudiantes.';

-- 2. Cada borrador tal como llegó del generador. Es lo que permite medir cuánto lo cambia
--    el docente (la tasa de edición de EPICAS.md §2) aunque luego reescriba las actividades.
create table if not exists public.generaciones_sesion (
    id bigint generated by default as identity primary key,
    sesion_id bigint not null references public.sesiones_planificadas(id) on delete cascade,
    solicitada_por bigint references public.cuentas_usuario(id),
    modelo varchar(80) not null,
    version_prompt varchar(20) not null,
    indicaciones text,
    salida jsonb not null,
    intentos smallint not null default 1 check (intentos > 0),
    duracion_ms integer check (duracion_ms is null or duracion_ms >= 0),
    created_at timestamptz not null default now()
);

create index if not exists idx_generaciones_sesion_sesion
    on public.generaciones_sesion (sesion_id, created_at desc);

-- 3. Nudos: las pocas cosas de un borrador que necesitan la mirada del docente.
--    MINUTOS, PASOS, CRITERIOS y MATERIAL los detectan reglas fijas; SUPUESTO lo declara
--    el generador cuando tuvo que imaginar algo de la comunidad.
create table if not exists public.nudos_sesion (
    id bigint generated by default as identity primary key,
    sesion_id bigint not null references public.sesiones_planificadas(id) on delete cascade,
    generacion_id bigint not null references public.generaciones_sesion(id) on delete cascade,
    tipo varchar(12) not null
        check (tipo in ('MINUTOS', 'PASOS', 'CRITERIOS', 'MATERIAL', 'SUPUESTO')),
    pregunta text not null,
    fragmento text,
    estado varchar(12) not null default 'PENDIENTE'
        check (estado in ('PENDIENTE', 'ACEPTADO', 'CAMBIO')),
    respuesta text,
    resuelto_por bigint references public.cuentas_usuario(id),
    resuelto_at timestamptz,
    created_at timestamptz not null default now(),
    check (estado = 'PENDIENTE' or resuelto_at is not null)
);

create index if not exists idx_nudos_sesion_sesion on public.nudos_sesion (sesion_id);

-- 4. Autoría también en el DUA y los materiales, que ahora puede proponer el generador.
alter table public.sesiones_dua
    add column if not exists origen varchar(12) not null default 'DOCENTE'
        check (origen in ('DOCENTE', 'GENERADA'));

alter table public.sesiones_materiales
    add column if not exists origen varchar(12) not null default 'DOCENTE'
        check (origen in ('DOCENTE', 'GENERADA'));

-- 5. Igual que el resto del esquema: sin acceso directo de clientes; solo el backend.
alter table public.contextos_aula enable row level security;
alter table public.generaciones_sesion enable row level security;
alter table public.nudos_sesion enable row level security;

do $$
begin
    if exists (select 1 from pg_roles where rolname = 'anon') then
        execute 'revoke all on public.contextos_aula, public.generaciones_sesion, public.nudos_sesion from anon';
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
        execute 'revoke all on public.contextos_aula, public.generaciones_sesion, public.nudos_sesion from authenticated';
    end if;
end $$;
